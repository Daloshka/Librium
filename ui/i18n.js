  const order={ru:0,en:1};
  const locales={ru:'ru-RU',en:'en-GB'};
  function detect(){
    try{const saved=localStorage.getItem('librium-lang');if(order[saved]!==undefined)return saved;}catch{}
    const supplied=root.librium&&root.librium.language;
    if(order[supplied]!==undefined)return supplied;
    if(typeof process!=='undefined'&&order[process.env&&process.env.LIBRIUM_LANG]!==undefined)return process.env.LIBRIUM_LANG;
    const preferred=(root.navigator&&root.navigator.language)||'';
    return /^ru/i.test(preferred)?'ru':'en';
  }
  function t(key,params){
    const pair=strings[key];
    let text=pair?(pair[order[api.lang]]??pair[1]):key;
    if(params)for(const [name,value] of Object.entries(params))text=text.split('{'+name+'}').join(String(value));
    return text;
  }
  const setters={'data-i18n':(node,text)=>{node.textContent=text;},'data-i18n-title':(node,text)=>node.setAttribute('title',text),'data-i18n-placeholder':(node,text)=>node.setAttribute('placeholder',text),'data-i18n-aria':(node,text)=>node.setAttribute('aria-label',text),'data-i18n-label':(node,text)=>{node.dataset.label=text;}};
  function apply(scope){
    const target=scope||(typeof document!=='undefined'?document:null);
    if(!target||!target.querySelectorAll)return;
    if(typeof document!=='undefined'&&document.documentElement)document.documentElement.lang=api.lang;
    for(const [attribute,set] of Object.entries(setters))for(const node of target.querySelectorAll('['+attribute+']'))set(node,t(node.getAttribute(attribute)));
  }
  function set(lang){if(lang!=='ru'&&lang!=='en')return api.lang;api.lang=lang;api.locale=locales[lang];apply();return api.lang;}
  const api={lang:'en',locale:locales.en,strings,t,apply,set};
  set(detect());
