const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('librium', {
  request: (path, method = 'GET', body) => ipcRenderer.invoke('api', path, method, body),
  saveCertificate: () => ipcRenderer.invoke('save-ca'),
  copy: text => ipcRenderer.invoke('copy', text),
  saveMedia: (id,side) => ipcRenderer.invoke('save-media',id,side),
  exportWs: id => ipcRenderer.invoke('export-ws',id),
  saveWsMessage: (id,messageId) => ipcRenderer.invoke('save-ws-message',id,messageId),
  saveWsInflated: (id,messageId,params) => ipcRenderer.invoke('save-ws-inflated',id,messageId,params),
  loadFilterSessions: () => ipcRenderer.invoke('filter-sessions-load'),
  saveFilterSessions: value => ipcRenderer.invoke('filter-sessions-save',value),
  openUrl: url => ipcRenderer.invoke('open-url', url),
  mobileStatus: () => ipcRenderer.invoke('mobile-status'),
  mobileEnable: address => ipcRenderer.invoke('mobile-enable', address),
  mobileDisable: () => ipcRenderer.invoke('mobile-disable'),
  reportError: message => ipcRenderer.invoke('report-error', message),
  captureStatus: () => ipcRenderer.invoke('capture-status'),
  captureTarget: () => ipcRenderer.invoke('capture-target'),
  captureSelect: () => ipcRenderer.invoke('capture-select'),
  captureLaunch: (port,startup) => ipcRenderer.invoke('capture-launch',port,startup),
  captureConnect: (port,mode,startup) => ipcRenderer.invoke('capture-connect',port,mode,startup),
  captureDisconnect: () => ipcRenderer.invoke('capture-disconnect'),
  captureMajestic: (port,startup) => ipcRenderer.invoke('capture-majestic',port,startup),
});
